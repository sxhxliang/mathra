//! Text kerned as TeX kerns it: the pairs of letters, digits and punctuation that the TFM of TeX's
//! text fonts kern, in em, for OT1 Computer Modern (`cmr10`, `cmbx10`, LaTeX's default) and T1
//! Latin Modern (`ec-lmr10`, `ec-lmbx10`, `\usepackage[T1]{fontenc}`). From `tftopl` of TeX Live's
//! fonts.

/// Which of TeX's kerning tables text is set with.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum TextKerning {
    /// None: each glyph by its advance.
    #[default]
    None,
    /// OT1 Computer Modern, LaTeX's default.
    Ot1,
    /// T1 (Latin Modern or EC), with `\usepackage[T1]{fontenc}`.
    T1,
}

/// The kern between `a` and `b`, in em, in roman or bold.
pub fn kern(kerning: TextKerning, bold: bool, a: char, b: char) -> f32 {
    let table = match (kerning, bold) {
        (TextKerning::None, _) => return 0.0,
        (TextKerning::Ot1, false) => OT1_ROMAN,
        (TextKerning::Ot1, true) => OT1_BOLD,
        (TextKerning::T1, false) => T1_ROMAN,
        (TextKerning::T1, true) => T1_BOLD,
    };
    table.binary_search_by(|&(x, y, _)| (x, y).cmp(&(a, b))).map_or(0.0, |i| table[i].2)
}

