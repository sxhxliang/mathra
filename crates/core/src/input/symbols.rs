#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Symbol {
    pub symbol: char,
    pub class: Class,
}

const fn s(symbol: char, class: Class) -> Option<Symbol> {
    Some(Symbol { symbol, class })
}

/// Characters typed directly into the equation.
pub fn character(c: char) -> Option<Symbol> {
    use Class::*;
    match c {
        '+' | '±' | '∓' | '×' | '÷' | '·' | '∗' | '∘' | '∪' | '∩' | '⊕' | '⊗' | '∧' | '∨' => s(c, Bin),
        '-' | '−' | '–' => s('−', Bin),
        '*' => s('∗', Bin),
        '/' => s('/', Ord),
        '=' | '<' | '>' | ':' | '≤' | '≥' | '≠' | '≈' | '≡' | '∼' | '≅' | '∝' | '→' | '←' | '↔' | '⇒' | '⇐' | '⇔' | '∈' | '∉' | '⊂' | '⊃' | '⊆' | '⊇' | '⇌' | '↑' | '↓' | '⟶'
        | '∥' | '⊥' | '≃' | '≪' | '≫' => s(c, Rel),
        '(' | '[' | '⟨' => s(c, Open),
        ')' | ']' | '⟩' | '!' | '?' => s(c, Close),
        ',' | ';' => s(c, Punct),
        '.' | '|' | '\'' | '°' | '%' | '∞' | '∅' | '∂' | '∇' | '∀' | '∃' | '¬' | '△' | '∠' | '…' | '⋯' | '"' | '@' | '`' | '™' | '€' | '£' | '§' | '¶' | '•' | '★' | '✓' | '✗' => {
            s(c, Ord)
        }
        _ => None,
    }
}

