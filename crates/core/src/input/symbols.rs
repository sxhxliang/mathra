pub fn delimiter_char(c: char) -> Option<Option<char>> {
    match c {
        '.' => Some(None),
        '(' | ')' | '[' | ']' | '|' | '/' | '<' | '>' | '⟨' | '⟩' | '‖' => Some(Some(match c {
            '<' => '⟨',
            '>' => '⟩',
            other => other,
        })),
        _ => None,
    }
}

