/// The commands by name, and the class of each character.
type Table = (HashMap<&'static str, Symbol>, HashMap<char, Class>);

fn command_table() -> &'static Table {
    static TABLE: OnceLock<Table> = OnceLock::new();
    TABLE.get_or_init(|| {
        let mut by_name = HashMap::new();
        let mut by_char = HashMap::new();
        for &(name, symbol, class) in COMMANDS {
            by_name.entry(name).or_insert(Symbol { symbol, class });
            by_char.entry(symbol).or_insert(class);
        }
        (by_name, by_char)
    })
}

/// Commands that are a single symbol.
pub fn command(name: &str) -> Option<Symbol> {
    command_table().0.get(name).copied()
}

/// Atom class of a character written directly or produced by a command: `≰` is a relation.
pub fn class_of_char(c: char) -> Option<Class> {
    character(c).map(|s| s.class).or_else(|| command_table().1.get(&c).copied())
}

