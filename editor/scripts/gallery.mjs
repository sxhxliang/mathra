// Writes src/gallery.ts from the repository's gallery (corpus/gallery.json): node scripts/gallery.mjs
// test/gallery.test.ts checks that the two still match.
import { readFileSync, writeFileSync } from "node:fs";

const gallery = JSON.parse(readFileSync(new URL("../../corpus/gallery.json", import.meta.url), "utf8"));
const groups = gallery.map((g) => ({ id: g.id, title: g.title, intro: g.intro ?? "", rows: g.rows.map((r) => ({ name: r.name ?? "", caption: r.caption, locale: r.locale ?? "en", input: r.input ?? "latex", options: r.options ?? {}, tex: r.tex })) }));
const out = `// Generated by scripts/gallery.mjs from corpus/gallery.json: do not edit by hand.
// The examples of mathra's gallery, to start from in the editor.

export interface GalleryExample {
  name: string;
  caption: string;
  /** The language the example is written for (its rules, its speech). */
  locale: string;
  /** "latex", or "mathml" and "asciimath", which the editor shows but does not edit. */
  input: string;
  /** mathra's options the example is drawn with (a maximum width…). */
  options: { maxWidth?: number };
  tex: string;
}

export interface GalleryGroup {
  id: string;
  title: string;
  intro: string;
  rows: GalleryExample[];
}

export const GALLERY: GalleryGroup[] = ${JSON.stringify(groups, null, 2)};
`;
writeFileSync(new URL("../src/gallery.ts", import.meta.url), out);
console.log(`src/gallery.ts: ${groups.length} groups, ${groups.reduce((n, g) => n + g.rows.length, 0)} examples`);
